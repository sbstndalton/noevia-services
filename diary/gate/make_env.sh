#!/usr/bin/env bash
# Write gate/.env.gate (gitignored, mode 600) with FRESH random test values for DIARY_TENANT_KEY and
# DIARY_AUTH_TOKEN. Prints key names only, never values.
#
#   make_env.sh --no-inference [--force]     inference URLs point at an unresolvable name (smoke)
#   make_env.sh [--force]                    inference from the caller's environment:
#       GATE_LLM_BASE_URL GATE_CHAT_MODEL GATE_EMBED_BASE_URL GATE_EMBED_MODEL   (required)
#       GATE_LLM_API_KEY GATE_AUX_BASE_URL GATE_AUX_MODEL GATE_EMBED_PROFILE      (optional)
#       GATE_EMBED_LOAD_URL GATE_KEV_LOAD_URL GATE_AUX_LOAD_URL  (default: the base URLs without /v1)
set -euo pipefail
GATE=$(cd "$(dirname "$0")" && pwd)
OUT="$GATE/.env.gate"
INFERENCE=1
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --no-inference) INFERENCE=0 ;;
    --force) FORCE=1 ;;
    *) echo "usage: $0 [--no-inference] [--force]" >&2; exit 2 ;;
  esac
done
if [ -e "$OUT" ] && [ "$FORCE" != 1 ]; then
  echo "$OUT exists; pass --force to replace it with fresh values" >&2
  exit 1
fi
rand() { head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
DISABLED=http://gate-inference-disabled.invalid:9/v1
if [ "$INFERENCE" = 1 ]; then
  for k in GATE_LLM_BASE_URL GATE_CHAT_MODEL GATE_EMBED_BASE_URL GATE_EMBED_MODEL; do
    if [ -z "${!k:-}" ]; then echo "$k is required (or pass --no-inference)" >&2; exit 2; fi
  done
  llm="$GATE_LLM_BASE_URL"; chat="$GATE_CHAT_MODEL"; embed="$GATE_EMBED_BASE_URL"; embed_model="$GATE_EMBED_MODEL"
  aux="${GATE_AUX_BASE_URL:-$llm}"; aux_model="${GATE_AUX_MODEL:-$chat}"; profile="${GATE_EMBED_PROFILE:-}"
  api_key="${GATE_LLM_API_KEY:-}"
  embed_load="${GATE_EMBED_LOAD_URL:-${embed%/v1}}"; kev_load="${GATE_KEV_LOAD_URL:-${llm%/v1}}"
  aux_load="${GATE_AUX_LOAD_URL:-${aux%/v1}}"
else
  llm="$DISABLED"; chat=gate-disabled; embed="$DISABLED"; embed_model=gate-disabled
  aux="$DISABLED"; aux_model=gate-disabled; profile=""; api_key=""; embed_load=""; kev_load=""; aux_load=""
fi
umask 077
tmp=$(mktemp "$GATE/.env.gate.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by make_env.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ); test values only, never production."
  echo "DIARY_AUTH_TOKEN=$(rand)"
  echo "DIARY_TENANT_KEY=$(rand)"
  echo "LLM_BASE_URL=$llm"
  echo "LLM_API_KEY=$api_key"
  echo "LLM_CHAT_MODEL=$chat"
  echo "LLM_AUX_BASE_URL=$aux"
  echo "LLM_AUX_API_KEY=$api_key"
  echo "LLM_AUX_MODEL=$aux_model"
  echo "LLM_EMBED_BASE_URL=$embed"
  echo "LLM_EMBED_MODEL=$embed_model"
  [ -n "$profile" ] && echo "LLM_EMBED_PROFILE=$profile"
  echo "GATE_EMBED_LOAD_URL=$embed_load"
  echo "GATE_KEV_LOAD_URL=$kev_load"
  echo "GATE_AUX_LOAD_URL=$aux_load"
} > "$tmp"
chmod 600 "$tmp"
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $OUT (mode 600; inference: $([ "$INFERENCE" = 1 ] && echo on || echo off)); keys: $(cut -d= -f1 "$OUT" | grep -v '^#' | tr '\n' ' ')"
